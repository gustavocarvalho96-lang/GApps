// Integration against local Wrangler + local D1 only. Never point this test at production.
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE });
const url = 'http://127.0.0.1:8789/';
const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const login = async p => { await p.goto(url); await p.locator('#password').fill('local-test-token'); await p.locator('#loginButton').click(); await p.locator('#workspace').waitFor({ state: 'visible' }); };
const title = 'Teste Suporte ' + Date.now();
const text = '<img src=x onerror=alert(1)>\nIdeia para lembrar.';
try {
  await page.goto(url);
  await page.locator('#password').fill('incorrect'); await page.locator('#loginButton').click();
  await page.getByText('Senha incorreta ou sessão encerrada.', { exact: true }).waitFor();
  assert.equal(await page.locator('#workspace').isVisible(), false);
  await login(page);
  await page.locator('#newNote').click();
  await page.locator('#title').fill(title); await page.locator('#body').fill(text); await page.locator('#app').selectOption('Plantão'); await page.locator('#priority').selectOption('Alta');
  await page.locator('#saveNote').click(); await page.locator('#editor').waitFor({ state: 'hidden' });
  const card = page.locator('.note').filter({ hasText: title });
  await card.waitFor(); assert.equal(await card.locator('img').count(), 0); assert.equal(await card.locator('p').textContent(), text);
  await page.locator('#search').fill('sem resultado'); await page.locator('#empty').waitFor({ state: 'visible' }); await page.locator('#search').fill('');
  await page.locator('#appFilter').selectOption('Fluxo'); assert.equal(await page.locator('.note').count(), 0); await page.locator('#appFilter').selectOption('');
  await page.reload(); await page.locator('#loginPanel').waitFor({ state: 'visible' }); assert.equal(await page.locator('#workspace').isVisible(), false);
  await login(page);
  assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
  const second = await browser.newContext(); const other = await second.newPage(); await login(other);
  const otherCard = other.locator('.note').filter({ hasText: title });
  await card.getByRole('button', { name: 'Editar' }).click();
  await otherCard.getByRole('button', { name: 'Editar' }).click(); await other.locator('#noteStatus').selectOption('Concluída'); await other.locator('#saveNote').click(); await other.locator('#editor').waitFor({ state: 'hidden' });
  await page.locator('#body').fill('Rascunho antigo preservado'); await page.locator('#saveNote').click();
  await page.locator('#editorStatus').filter({ hasText: 'outro dispositivo' }).waitFor(); assert.equal(await page.locator('#body').inputValue(), 'Rascunho antigo preservado');
  page.once('dialog', dialog => dialog.accept()); await page.locator('#cancelEditor').click(); await page.locator('#refresh').click(); await card.getByText('Concluída', { exact: true }).waitFor();
  await card.getByRole('button', { name: 'Editar' }).click(); await page.locator('#body').fill('Alteração sem internet');
  await context.setOffline(true); await page.locator('#saveNote').click(); await page.locator('#editorStatus').filter({ hasText: 'Sem conexão' }).waitFor(); assert.equal(await page.locator('#body').inputValue(), 'Alteração sem internet');
  await context.setOffline(false); await page.locator('#saveNote').click(); await page.locator('#editor').waitFor({ state: 'hidden' }); await card.getByText('Alteração sem internet', { exact: true }).waitFor();
  await mkdir('cloudflare/suporte/.wrangler/qa', { recursive: true });
  await page.screenshot({ path: 'cloudflare/suporte/.wrangler/qa/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await card.getByRole('button', { name: 'Editar' }).click();
  assert.equal(await page.locator('#editor').evaluate(el => el.scrollWidth <= el.clientWidth), true);
  await page.screenshot({ path: 'cloudflare/suporte/.wrangler/qa/mobile-editor.png', fullPage: true });
  await page.locator('#cancelEditor').click();
  await page.screenshot({ path: 'cloudflare/suporte/.wrangler/qa/mobile.png', fullPage: true });
  await card.getByRole('button', { name: 'Editar' }).click(); page.once('dialog', dialog => dialog.accept()); await page.locator('#deleteNote').click(); await page.locator('#editor').waitFor({ state: 'hidden' }); assert.equal(await card.count(), 0);
  await page.locator('#logout').click(); assert.equal(await page.locator('#workspace').isVisible(), false);
  assert.deepEqual(errors, []);
  await second.close();
  console.log('PASS: senha, CRUD, persistência, filtros, duas sessões, conflito, falha de rede, XSS literal, logout e layout móvel.');
} finally { await browser.close(); }
